#!/usr/bin/env python3
"""Build AB CSS and the Figma token manifest from tokens/brand.json."""
from pathlib import Path
import json

ROOT=Path(__file__).resolve().parents[1]

def luminance(h):
    rgb=[int(h[i:i+2],16)/255 for i in (1,3,5)]
    rgb=[x/12.92 if x<=.04045 else ((x+.055)/1.055)**2.4 for x in rgb]
    return sum(x*w for x,w in zip(rgb,(.2126,.7152,.0722)))

def contrast(a,b):
    hi,lo=sorted((luminance(a),luminance(b)),reverse=True)
    return (hi+.05)/(lo+.05)

def build():
    brand=json.loads((ROOT/'tokens/brand.json').read_text())
    palette,sem=brand['palette'],brand['semantic']
    css=['/* Generated by scripts/build_tokens.py. Edit brand.json. */','@font-face { font-family: Sora; src: url("../assets/fonts/Sora-Variable.woff") format("woff"); font-weight: 100 800; font-style: normal; font-display: swap; }',':root {']
    collections=[]
    primitives=[]
    for name,value in palette.items():
        css.append(f'  --ab-palette-{name}: {value};')
        primitives.append({'name':name,'type':'COLOR','values':{'Value':value},'scopes':[],'css':f'--ab-palette-{name}'})
    collections.append({'name':'AB / Primitives','modes':['Value'],'tokens':primitives})
    semantic=[]
    for name,values in sem.items():
        css.append(f'  --ab-color-{name}: var(--ab-palette-{values["Light"]});')
        scopes=['TEXT_FILL'] if name in ('fg','muted','error','success') else ['STROKE_COLOR'] if name in ('border','focus') else ['FRAME_FILL','SHAPE_FILL','TEXT_FILL']
        semantic.append({'name':name,'type':'COLOR','values':{mode:{'alias':f'AB / Primitives/{v}'} for mode,v in values.items()},'scopes':scopes,'css':f'--ab-color-{name}'})
    collections.append({'name':'AB / Color','modes':['Light','Dark'],'tokens':semantic})
    dimensions=[]
    for category,values in brand['dimensions'].items():
        for name,value in values.items():
            css.append(f'  --ab-{category}-{name}: {value}px;')
            scopes=['GAP'] if category=='space' else ['CORNER_RADIUS'] if category=='radius' else ['WIDTH_HEIGHT']
            dimensions.append({'name':f'{category}/{name}','type':'FLOAT','values':{'Value':value},'scopes':scopes,'css':f'--ab-{category}-{name}'})
    collections.append({'name':'AB / Geometry','modes':['Value'],'tokens':dimensions})
    for name,ms in brand['motion']['duration_ms'].items():
        css.append(f'  --ab-motion-{name}: {ms}ms;')
    css += ['  --ab-font-family: Sora, system-ui, sans-serif;','  --ab-motion-ease-out: cubic-bezier(.22, 1, .36, 1);','}', '[data-theme="dark"] {']
    css += [f'  --ab-color-{name}: var(--ab-palette-{values["Dark"]});' for name,values in sem.items()]
    css += ['}','@media (prefers-reduced-motion: reduce) {', '  :root { --ab-motion-fast: 0ms; --ab-motion-state: 0ms; --ab-motion-signature: 0ms; }','}','']
    (ROOT/'tokens/brand.css').write_text('\n'.join(css))
    manifest={'schema':'ab-figma-tokens/1','collections':collections,'textStyles':brand['typography']['styles']}
    (ROOT/'tokens/brand.tokens.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    pairs=[('white','ink'),('white','blue'),('blue','white'),('blue','ink'),('focus','ink'),('muted','white'),('line','ink'),('error','white'),('success','white')]
    report=[]
    for fg,bg in pairs:
        ratio=contrast(palette[fg],palette[bg])
        report.append({'foreground':palette[fg],'background':palette[bg],'ratio':ratio,'text_AA_4_5':ratio>=4.5,'large_text_AA_3':ratio>=3})
    (ROOT/'docs/contrast.json').write_text(json.dumps({'formula':'WCAG relative luminance in sRGB; no rounded threshold comparison','source':'https://www.w3.org/WAI/WCAG22/Understanding/contrast-minimum.html','pairs':report},indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__':
    build()
